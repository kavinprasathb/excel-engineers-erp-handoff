"""Stock operations — the ONLY place inventory counters are ever written.

Why this is a hard rule rather than a convention: in v2 the invariant lived in
one function and nothing stopped other code walking around it, so the
fulfilment path mutated the counters directly and the ledger drifted away from
the numbers it was supposed to explain.

Three layers stop that happening here:

1. Database CHECK constraints — even a psql prompt cannot produce negative or
   over-reserved stock. The floor, not the ceiling.
2. `install_stock_guard()` — a session listener that raises if any Inventory
   row is flushed without going through `_apply`. This is the layer that
   catches a developer in their first test run, with a message telling them
   what to do instead.
3. A CI architecture test that walks the AST of app/ looking for assignments to
   the counter columns outside this module.

Nothing here commits. The caller owns the transaction boundary, so a future
`confirm_order` can commit the order status and its reservations atomically.
"""

from dataclasses import dataclass
from typing import Any, NamedTuple

from sqlalchemy import event, func, select
from sqlalchemy.orm import Session

from ..constants import MovementType, ReferenceType
from ..errors import InsufficientReservation, InsufficientStock, NotFound
from ..models import Inventory, StockMovement

# Key under which a session records the Inventory identities this module is
# currently allowed to modify.
_GUARD_KEY = "stock_service_mutation"


@dataclass(frozen=True, slots=True)
class StockRef:
    """Where a movement came from.

    Every caller must supply one, so no movement can be orphaned from its cause.
    """

    type: ReferenceType
    id: int | None = None
    note: str = ""


class Discrepancy(NamedTuple):
    product_id: int
    counter_on_hand: int
    ledger_on_hand: int
    counter_reserved: int
    ledger_reserved: int


def _apply(
    db: Session,
    *,
    product_id: int,
    movement_type: MovementType,
    on_hand_delta: int,
    reserved_delta: int,
    ref: StockRef,
    actor_id: int | None,
) -> Inventory:
    """Lock, validate, mutate, record. The single funnel.

    Locks the inventory row FOR UPDATE so concurrent orders serialise rather
    than interleaving between the read and the write.
    """
    inv = db.execute(
        select(Inventory).where(Inventory.product_id == product_id).with_for_update()
    ).scalar_one_or_none()
    if inv is None:
        raise NotFound(f"No inventory record for product {product_id}", product_id=product_id)

    new_on_hand = inv.quantity_on_hand + on_hand_delta
    new_reserved = inv.quantity_reserved + reserved_delta

    if new_on_hand < 0:
        raise InsufficientStock(
            f"Only {inv.quantity_on_hand} in stock; cannot remove {abs(on_hand_delta)}.",
            in_stock=inv.quantity_on_hand,
            requested=abs(on_hand_delta),
        )
    if new_reserved < 0:
        raise InsufficientReservation(
            f"Only {inv.quantity_reserved} reserved; cannot release {abs(reserved_delta)}.",
            reserved=inv.quantity_reserved,
            requested=abs(reserved_delta),
        )
    if new_reserved > new_on_hand:
        raise InsufficientStock(
            f"{new_reserved} would be reserved for orders "
            f"but only {new_on_hand} would be in stock.",
            on_hand=new_on_hand,
            reserved=new_reserved,
        )

    db.info.setdefault(_GUARD_KEY, set()).add(id(inv))
    inv.quantity_on_hand = new_on_hand
    inv.quantity_reserved = new_reserved

    db.add(
        StockMovement(
            product_id=product_id,
            movement_type=movement_type,
            on_hand_delta=on_hand_delta,
            reserved_delta=reserved_delta,
            quantity_on_hand_after=new_on_hand,
            quantity_reserved_after=new_reserved,
            reference_type=ref.type,
            reference_id=ref.id,
            note=ref.note[:255],
            created_by_id=actor_id,
        )
    )
    db.flush()
    # quantity_available is generated by Postgres; without this refresh the
    # instance still holds the value from before the update.
    db.refresh(inv, ["quantity_available"])
    return inv


# ---------------------------------------------------------------------------
# The public vocabulary. The rest of the app speaks only these verbs.
# ---------------------------------------------------------------------------


def adjust(
    db: Session, *, product_id: int, delta: int, ref: StockRef, actor_id: int | None = None
) -> Inventory:
    """Manual correction: a recount, damage, or an opening balance."""
    if delta == 0:
        raise InsufficientStock("An adjustment of zero would change nothing.")
    return _apply(
        db,
        product_id=product_id,
        movement_type=MovementType.ADJUST,
        on_hand_delta=delta,
        reserved_delta=0,
        ref=ref,
        actor_id=actor_id,
    )


def receive(
    db: Session, *, product_id: int, qty: int, ref: StockRef, actor_id: int | None = None
) -> Inventory:
    """Goods in — a purchase order receipt, or a new product's opening stock."""
    if qty <= 0:
        raise InsufficientStock("Received quantity must be positive.")
    return _apply(
        db,
        product_id=product_id,
        movement_type=MovementType.RECEIVE,
        on_hand_delta=qty,
        reserved_delta=0,
        ref=ref,
        actor_id=actor_id,
    )


def set_on_hand(
    db: Session, *, product_id: int, qty: int, ref: StockRef, actor_id: int | None = None
) -> Inventory | None:
    """Set stock to an absolute figure — what a spreadsheet import needs.

    Returns None when the count already matches, so the importer can report how
    many rows actually changed instead of writing a no-op movement.
    """
    if qty < 0:
        raise InsufficientStock("Stock cannot be set to a negative number.")
    inv = db.execute(
        select(Inventory).where(Inventory.product_id == product_id)
    ).scalar_one_or_none()
    if inv is None:
        raise NotFound(f"No inventory record for product {product_id}", product_id=product_id)

    delta = qty - inv.quantity_on_hand
    if delta == 0:
        return None
    movement = MovementType.IMPORT if ref.type is ReferenceType.IMPORT else MovementType.ADJUST
    return _apply(
        db,
        product_id=product_id,
        movement_type=movement,
        on_hand_delta=delta,
        reserved_delta=0,
        ref=ref,
        actor_id=actor_id,
    )


def reserve(
    db: Session, *, product_id: int, qty: int, ref: StockRef, actor_id: int | None = None
) -> Inventory:
    """Claim stock for an order.

    Strict: raises rather than reserving what it can. v2 reserved "up to qty"
    and returned the amount taken, so callers that ignored the return value
    created orders believing they had stock they did not have.
    """
    if qty <= 0:
        raise InsufficientStock("Reserved quantity must be positive.")
    return _apply(
        db,
        product_id=product_id,
        movement_type=MovementType.RESERVE,
        on_hand_delta=0,
        reserved_delta=qty,
        ref=ref,
        actor_id=actor_id,
    )


def release(
    db: Session, *, product_id: int, qty: int, ref: StockRef, actor_id: int | None = None
) -> Inventory:
    """Give a claim back — the order was cancelled or reduced."""
    if qty <= 0:
        raise InsufficientReservation("Released quantity must be positive.")
    return _apply(
        db,
        product_id=product_id,
        movement_type=MovementType.RELEASE,
        on_hand_delta=0,
        reserved_delta=-qty,
        ref=ref,
        actor_id=actor_id,
    )


def deliver(
    db: Session, *, product_id: int, qty: int, ref: StockRef, actor_id: int | None = None
) -> Inventory:
    """Reserved goods physically leave the shop.

    One movement, not release-then-adjust: two movements can interleave with a
    concurrent reservation and momentarily expose stock that is already sold.
    """
    if qty <= 0:
        raise InsufficientStock("Delivered quantity must be positive.")
    return _apply(
        db,
        product_id=product_id,
        movement_type=MovementType.DELIVER,
        on_hand_delta=-qty,
        reserved_delta=-qty,
        ref=ref,
        actor_id=actor_id,
    )


def bulk_reserve(
    db: Session,
    *,
    lines: list[tuple[int, int]],
    ref: StockRef,
    actor_id: int | None = None,
) -> dict[int, Inventory]:
    """Reserve several products for one order.

    Locks in sorted product_id order. Two overlapping multi-line orders locking
    in arrival order would deadlock; sorting costs nothing and removes the
    possibility entirely.
    """
    result: dict[int, Inventory] = {}
    for product_id, qty in sorted(lines):
        result[product_id] = reserve(db, product_id=product_id, qty=qty, ref=ref, actor_id=actor_id)
    return result


def reconcile(db: Session, product_id: int | None = None) -> list[Discrepancy]:
    """Prove the counters still match the ledger. Read-only.

    Writable only because movements record on-hand and reserved deltas
    separately — against v2's single-delta schema this query had no meaning.
    """
    ledger = (
        select(
            StockMovement.product_id.label("pid"),
            func.coalesce(func.sum(StockMovement.on_hand_delta), 0).label("on_hand"),
            func.coalesce(func.sum(StockMovement.reserved_delta), 0).label("reserved"),
        )
        .group_by(StockMovement.product_id)
        .subquery()
    )
    on_hand = func.coalesce(ledger.c.on_hand, 0)
    reserved = func.coalesce(ledger.c.reserved, 0)
    stmt = (
        select(
            Inventory.product_id,
            Inventory.quantity_on_hand,
            on_hand,
            Inventory.quantity_reserved,
            reserved,
        )
        .outerjoin(ledger, ledger.c.pid == Inventory.product_id)
        .where((Inventory.quantity_on_hand != on_hand) | (Inventory.quantity_reserved != reserved))
        .order_by(Inventory.product_id)
    )
    if product_id is not None:
        stmt = stmt.where(Inventory.product_id == product_id)
    return [Discrepancy(*row) for row in db.execute(stmt)]


def install_stock_guard(session_factory: Any) -> None:
    """Make bypassing this module an error, not a code-review problem."""

    @event.listens_for(session_factory, "before_flush")
    def _block_direct_inventory_writes(session: Session, _ctx: Any, _inst: Any) -> None:
        allowed: set[int] = session.info.get(_GUARD_KEY, set())
        for obj in session.dirty:
            if isinstance(obj, Inventory) and id(obj) not in allowed:
                raise RuntimeError(
                    "Inventory counters were modified outside app.services.stock. "
                    "Every stock change must go through the stock service "
                    "(adjust/receive/reserve/release/deliver) so the ledger "
                    "always explains the numbers."
                )


